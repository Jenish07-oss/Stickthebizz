import fs from 'fs';
import path from 'path';

// Minimal valid silent/bell MP3 frame header and sync pattern
// 128 kbps 44.1 kHz stereo MP3 header: FF FB 90 64 ...
const mp3Bytes = Buffer.from([
  0xff, 0xfb, 0x90, 0x64, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0x58, 0x69, 0x6e, 0x67, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
  0x00, 0x00, 0x01, 0xa1, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
  0xff, 0xfb, 0x90, 0x64, 0x00, 0x03, 0x48, 0x00, 0x00, 0x00, 0x00, 0x00,
]);

const soundsDir = path.join(process.cwd(), 'public', 'sounds');
if (!fs.existsSync(soundsDir)) {
  fs.mkdirSync(soundsDir, { recursive: true });
}

fs.writeFileSync(path.join(soundsDir, 'chime.mp3'), mp3Bytes);
console.log('Created public/sounds/chime.mp3');

